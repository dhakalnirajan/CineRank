#!/usr/bin/env python3
"""Single-command CineRank launcher for Windows, macOS and Linux.

Usage:
  python cinerank.py              # build and start the full stack
  python cinerank.py up            # same as above
  python cinerank.py down          # stop containers, preserve named data volumes
  python cinerank.py status
  python cinerank.py logs [api|web|worker|db|redis]
  python cinerank.py rebuild
  python cinerank.py migrate
  python cinerank.py backfill --limit 100
"""
from __future__ import annotations

import argparse
from pathlib import Path
import secrets
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parent
ENV_FILE = ROOT / ".env"


def _default_env() -> str:
    return "\n".join([
        "# Generated by python cinerank.py for local HTTP development.",
        "# For production, set ENVIRONMENT=production and AUTH_COOKIE_SECURE=true",
        "# behind HTTPS before exposing this service publicly.",
        "ENVIRONMENT=development",
        "LOG_LEVEL=INFO",
        f"SECRET_KEY={secrets.token_urlsafe(64)}",
        f"JWT_SECRET_KEY={secrets.token_urlsafe(64)}",
        "POSTGRES_DB=cinerank",
        "POSTGRES_USER=cinerank",
        f"POSTGRES_PASSWORD={secrets.token_urlsafe(36)}",
        f"REDIS_PASSWORD={secrets.token_urlsafe(36)}",
        f"GRAFANA_ADMIN_PASSWORD={secrets.token_urlsafe(36)}",
        "PUBLIC_HTTP_PORT=8080",
        "CORS_ORIGINS=http://localhost:8080",
        "FRONTEND_BASE_URL=http://localhost:8080",
        "AUTH_COOKIE_SECURE=false",
        "AUTH_COOKIE_SAMESITE=lax",
        "ACCESS_TOKEN_EXPIRE_MINUTES=15",
        "REFRESH_TOKEN_EXPIRE_DAYS=30",
        "TMDB_API_KEY=",
        "TMDB_READ_ACCESS_TOKEN=",
        "MODEL_INFERENCE_USE_GPU=false",
        "MODEL_INFERENCE_REQUIRE_GPU=false",
        "MODEL_INFERENCE_CACHE_SIZE=1024",
        "",
    ])


def ensure_env() -> None:
    if not ENV_FILE.exists():
        ENV_FILE.write_text(_default_env(), encoding="utf-8")
        try:
            ENV_FILE.chmod(0o600)
        except OSError:
            pass
        print("Created .env with unique local secrets and HTTP localhost cookie settings.")
        return

    content = ENV_FILE.read_text(encoding="utf-8")
    placeholders = ("REPLACE_WITH_", "CHANGE-ME-IN-PRODUCTION")
    if any(value in content for value in placeholders):
        raise SystemExit(
            "Your .env still contains placeholder secrets. Replace SECRET_KEY, "
            "JWT_SECRET_KEY, POSTGRES_PASSWORD, REDIS_PASSWORD and GRAFANA_ADMIN_PASSWORD, or move the file aside and "
            "run this launcher to generate local development secrets."
        )
    additions = []
    production = any(line.strip() == "ENVIRONMENT=production" for line in content.splitlines())
    for variable in ("REDIS_PASSWORD", "GRAFANA_ADMIN_PASSWORD"):
        if not any(line.startswith(f"{variable}=") for line in content.splitlines()):
            if production:
                raise SystemExit(f"Set a strong {variable} in the production .env before starting CineRank.")
            additions.append(f"{variable}={secrets.token_urlsafe(36)}")
    if additions:
        ENV_FILE.write_text(content.rstrip() + "\n" + "\n".join(additions) + "\n", encoding="utf-8")
        try:
            ENV_FILE.chmod(0o600)
        except OSError:
            pass


def docker_compose() -> list[str]:
    docker = shutil.which("docker")
    if not docker:
        raise SystemExit("Docker CLI not found. Install Docker Desktop (Windows/macOS) or Docker Engine + Compose v2.")
    probe = subprocess.run(
        [docker, "compose", "version"],
        cwd=ROOT,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
    )
    if probe.returncode != 0:
        raise SystemExit("Docker Compose v2 is unavailable. Update Docker Desktop or install the Compose plugin.\n" + probe.stdout)
    return [docker, "compose"]


def run(command: list[str], *, check: bool = True) -> int:
    print("$ " + " ".join(command), flush=True)
    result = subprocess.run(command, cwd=ROOT)
    if check and result.returncode != 0:
        raise SystemExit(result.returncode)
    return result.returncode


def main() -> int:
    parser = argparse.ArgumentParser(description="Build, launch and manage the complete CineRank stack.")
    parser.add_argument("command", nargs="?", default="up", choices=(
        "up", "start", "down", "stop", "restart", "status", "ps", "logs",
        "rebuild", "migrate", "seed", "backfill", "config",
    ))
    parser.add_argument("--no-build", action="store_true", help="Do not rebuild images when starting.")
    parser.add_argument("--tail", default="100", help="Number of log lines to show before following logs.")
    options, extra_args = parser.parse_known_args()

    compose = docker_compose()
    command = options.command

    ensure_env()

    if command in {"up", "start", "rebuild"}:
        run(compose + ["config", "--quiet"])
        args = ["up", "-d"]
        if command == "rebuild" or not options.no_build:
            args.append("--build")
        run(compose + args)
        run(compose + ["ps"])
        env = ENV_FILE.read_text(encoding="utf-8")
        port = 8080
        for line in env.splitlines():
            if line.startswith("PUBLIC_HTTP_PORT="):
                try:
                    port = int(line.split("=", 1)[1].strip())
                except ValueError:
                    pass
        print(f"\nCineRank web app: http://localhost:{port}")
        print("API is proxied through the same origin at /api/v1.")
        print("Use 'python cinerank.py logs' to follow service logs; 'down' preserves database/media volumes.")
        return 0

    if command in {"down", "stop"}:
        run(compose + ["down"])
        print("Containers stopped. Named PostgreSQL and media volumes were preserved.")
        return 0

    if command == "restart":
        run(compose + ["restart"])
        return 0

    if command in {"status", "ps"}:
        return run(compose + ["ps"], check=False)

    if command == "logs":
        return run(compose + ["logs", "--follow", f"--tail={options.tail}", *extra_args], check=False)

    if command == "migrate":
        run(compose + ["up", "-d", "db"])
        return run(compose + ["run", "--build", "--rm", "migrate"])

    if command == "seed":
        run(compose + ["up", "-d", "db"])
        run(compose + ["run", "--build", "--rm", "migrate"])
        return run(compose + ["run", "--build", "--rm", "catalogue-bootstrap"])

    if command == "backfill":
        if not extra_args:
            raise SystemExit("Usage: python cinerank.py backfill --limit 100 [--apply]")
        run(compose + ["up", "-d", "db"])
        run(compose + ["run", "--build", "--rm", "migrate"])
        return run(compose + [
            "run", "--build", "--rm", "worker", "python", "scripts/backfill_tmdb_metadata.py", *extra_args,
        ])

    if command == "config":
        return run(compose + ["config"], check=False)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
